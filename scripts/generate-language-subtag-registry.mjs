/**
 * Generates `packages/langtag/src/internal/registry-data.ts` from the IANA
 * Language Subtag Registry (RFC 5646 §3): the subtags registered for each
 * position, the `Preferred-Value` mappings and the `Suppress-Script`
 * values, as space-delimited string literals (pure declarations, so the
 * `./registry` entry stays tree-shakeable under `"sideEffects": false`).
 *
 *   node scripts/generate-language-subtag-registry.mjs [file-or-url] [--source "<provenance>"]
 *
 * With no argument it fetches the registry from IANA. A file argument (a
 * copy of the registry, e.g. the one CLDR vendors) is read as is; pass
 * `--source` to record where that copy came from. Run `vp fmt` after.
 */
import { readFileSync, writeFileSync } from "node:fs";

const IANA = "https://www.iana.org/assignments/language-subtag-registry/language-subtag-registry";
const OUTPUT = "packages/langtag/src/internal/registry-data.ts";

const args = process.argv.slice(2);
const sourceFlag = args.indexOf("--source");
const provenance = sourceFlag >= 0 ? args[sourceFlag + 1] : undefined;
const input = args.find((arg, index) => !arg.startsWith("--") && index !== sourceFlag + 1) ?? IANA;

const text = /^https?:/.test(input)
  ? await (await fetch(input)).text()
  : readFileSync(input, "utf8");

/** Appends a continuation line (one that starts with whitespace) to the last field's value. */
const continueField = (record, line) => {
  const values = record.fields.get(record.last);
  values[values.length - 1] += ` ${line.trim()}`;
  return record;
};

/** Adds a `Field: value` line; a line without a `:` is skipped. */
const addField = (record, line) => {
  const at = line.indexOf(":");
  if (at < 0) return record;
  const name = line.slice(0, at).trim();
  record.fields.set(name, [...(record.fields.get(name) ?? []), line.slice(at + 1).trim()]);
  return { fields: record.fields, last: name };
};

/** Folds one line into a record. */
const addLine = (record, line) =>
  /^\s/.test(line) && record.last !== undefined
    ? continueField(record, line)
    : addField(record, line);

/** Each record as a map of field name to values (a field may repeat). */
const records = text
  .split(/\r?\n%%\r?\n/)
  .map(
    (block) => block.split(/\r?\n/).reduce(addLine, { fields: new Map(), last: undefined }).fields,
  );

const fileDate = records[0].get("File-Date")?.[0];
if (fileDate === undefined) {
  console.error(`${input}: no File-Date, not a Language Subtag Registry`);
  process.exit(1);
}

/** A run of letters as a base-26 number (`aa` → 0, `ab` → 1). */
const toNumber = (letters) =>
  [...letters.toLowerCase()].reduce((total, letter) => total * 26 + letter.charCodeAt(0) - 97, 0);

/** The inverse of `toNumber`, `length` letters long, lowercase. */
const fromNumber = (value, length) =>
  Array.from({ length }, (_, index) =>
    String.fromCharCode(97 + (Math.floor(value / 26 ** (length - 1 - index)) % 26)),
  ).join("");

/** `letters` in the case pattern of `template` (`Qaaa` makes `qabx` → `Qabx`). */
const withCaseOf = (template, letters) =>
  [...letters]
    .map((letter, index) => (/[A-Z]/.test(template[index]) ? letter.toUpperCase() : letter))
    .join("");

/** `qaa..qtz` → every subtag in the range, in the range's case; a plain subtag → itself. */
const expand = (subtag) => {
  const [from, to] = subtag.split("..");
  if (to === undefined) return [subtag];
  const start = toNumber(from);
  return Array.from({ length: toNumber(to) - start + 1 }, (_, offset) =>
    withCaseOf(from, fromNumber(start + offset, from.length)),
  );
};

const byType = (type) => records.filter((record) => record.get("Type")?.[0] === type);
const subtagsOf = (type) =>
  byType(type)
    .flatMap((record) => expand(record.get("Subtag")[0]))
    .map((subtag) => subtag.toLowerCase());

/** `key:value` pairs for every record of `type` with a `Preferred-Value`. */
const preferredOf = (type, key) =>
  byType(type)
    .filter((record) => record.has("Preferred-Value"))
    .map((record) => `${record.get(key)[0].toLowerCase()}:${record.get("Preferred-Value")[0]}`);

// Subtags and preferred values are alphanumerics and `-`: nothing to escape.
const list = (values) => `" ${values.join(" ")} "`;

const suppress = byType("language")
  .filter((record) => record.has("Suppress-Script"))
  .map((record) => `${record.get("Subtag")[0].toLowerCase()}:${record.get("Suppress-Script")[0]}`);

const source = provenance ?? input;

writeFileSync(
  OUTPUT,
  `/**
 * The IANA Language Subtag Registry (RFC 5646 §3), as lookup strings.
 *
 * GENERATED by \`scripts/generate-language-subtag-registry.mjs\` — do not
 * edit by hand. Regenerate to update the snapshot.
 *
 * Source: ${source}
 * File-Date: ${fileDate}
 *
 * The registry is published by IANA without restriction. Each list is
 * space-delimited with a space at both ends, so a subtag \`x\` is
 * registered when the list contains \` x \`; subtags are lowercase, ranges
 * (\`qaa..qtz\`) are expanded. Each map is \`key:value\` pairs, key
 * lowercase, value in the registry's case.
 */

/** The registry's \`File-Date\`: the snapshot this data was taken from. */
export const FILE_DATE = "${fileDate}";

export const LANGUAGES = ${list(subtagsOf("language"))};
export const EXTLANGS = ${list(subtagsOf("extlang"))};
export const SCRIPTS = ${list(subtagsOf("script"))};
export const REGIONS = ${list(subtagsOf("region"))};
export const VARIANTS = ${list(subtagsOf("variant"))};

export const PREFERRED_LANGUAGES = ${list(preferredOf("language", "Subtag"))};
export const PREFERRED_EXTLANGS = ${list(preferredOf("extlang", "Subtag"))};
export const PREFERRED_SCRIPTS = ${list(preferredOf("script", "Subtag"))};
export const PREFERRED_REGIONS = ${list(preferredOf("region", "Subtag"))};
export const PREFERRED_VARIANTS = ${list(preferredOf("variant", "Subtag"))};
/** Whole grandfathered and redundant tags with a \`Preferred-Value\`. */
export const PREFERRED_TAGS = ${list([...preferredOf("grandfathered", "Tag"), ...preferredOf("redundant", "Tag")])};

export const SUPPRESS_SCRIPTS = ${list(suppress)};
`,
);
console.log(`${OUTPUT}: registry ${fileDate} from ${source}`);
